const express =
    require(
        "express"
    );


// =====================================================
// ROUTER
//
// Route นี้ถูกใช้งานผ่าน:
//
// /api/users
//
// =====================================================

const router =
    express.Router();


// =====================================================
// USER CONTROLLER
//
// Controller จัดการ:
//
// - ดึง User ทั้งหมด
// - ดึง User ตาม ID
// - สร้าง User
// - แก้ไข User
// - Reset Password
// - ลบ User
// =====================================================

const UserController =
    require(
        "../controllers/userController"
    );


// =====================================================
// AUTH MIDDLEWARE
//
// authenticate
//
// ตรวจสอบ:
//
// - Authorization Header
// - Bearer Token
// - JWT Token
//
// authorize
//
// ตรวจสอบสิทธิ์ของ User
// =====================================================

const {
    authenticate,
    authorize
} =
    require(
        "../middleware/auth"
    );


// =====================================================
// ROLE POLICY
//
// กำหนดสิทธิ์ User Management
//
// ADMIN
//
// - ดู User ทั้งหมด
// - ดู User ตาม ID
// - สร้าง User
// - แก้ไข User
// - Reset Password
// - ลบ User
//
// -----------------------------------------------------
//
// SUPERVISOR
//
// ไม่มีสิทธิ์จัดการ User
//
// -----------------------------------------------------
//
// EMPLOYEE
//
// ไม่มีสิทธิ์จัดการ User
//
// =====================================================
//
// IMPORTANT
//
// User Management เป็นข้อมูลความปลอดภัยของระบบ
//
// จึงกำหนดให้:
//
// ADMIN เท่านั้น
//
// =====================================================

const ROLE =
    {

        ADMIN:
            [
                "ADMIN"
            ]

    };


// =====================================================
// ALL USER ROUTES REQUIRE LOGIN
//
// ทุก API ด้านล่างต้อง Login ก่อน
//
// ถ้า:
//
// - ไม่มี Token
// - Token หมดอายุ
// - Token ไม่ถูกต้อง
//
// ระบบจะตอบ:
//
// 401 Unauthorized
//
// =====================================================

router.use(
    authenticate
);


// =====================================================
// GET ALL USERS
//
// GET:
//
// /api/users
//
// =====================================================
//
// ROLE:
//
// ADMIN ONLY
//
// =====================================================
//
// ใช้สำหรับ:
//
// - User Management Page
// - ดูรายการ User ทั้งหมด
//
// =====================================================

router.get(

    "/",

    authorize(
        ...ROLE.ADMIN
    ),

    UserController.getAll

);


// =====================================================
// CREATE USER
//
// POST:
//
// /api/users
//
// =====================================================
//
// ROLE:
//
// ADMIN ONLY
//
// =====================================================
//
// Body:
//
// {
//     username: "employee1",
//     password: "123456",
//     fullname: "Employee One",
//     role: "EMPLOYEE"
// }
//
// =====================================================

router.post(

    "/",

    authorize(
        ...ROLE.ADMIN
    ),

    UserController.create

);


// =====================================================
// RESET USER PASSWORD
//
// PUT:
//
// /api/users/:id/password
//
// =====================================================
//
// IMPORTANT
//
// Route นี้ต้องอยู่ก่อน:
//
// /:id
//
// เพื่อป้องกัน Express ตีความ:
//
// /1/password
//
// ผิดเป็น Route:
//
// /:id
//
// =====================================================
//
// ROLE:
//
// ADMIN ONLY
//
// =====================================================
//
// Body:
//
// {
//     password: "newpassword"
// }
//
// =====================================================

router.put(

    "/:id/password",

    authorize(
        ...ROLE.ADMIN
    ),

    UserController.resetPassword

);


// =====================================================
// GET USER BY ID
//
// GET:
//
// /api/users/:id
//
// =====================================================
//
// ROLE:
//
// ADMIN ONLY
//
// =====================================================
//
// ตัวอย่าง:
//
// /api/users/1
//
// =====================================================

router.get(

    "/:id",

    authorize(
        ...ROLE.ADMIN
    ),

    UserController.getById

);


// =====================================================
// UPDATE USER
//
// PUT:
//
// /api/users/:id
//
// =====================================================
//
// ROLE:
//
// ADMIN ONLY
//
// =====================================================
//
// ใช้สำหรับ:
//
// - แก้ไข Username
// - แก้ไข Full Name
// - แก้ไข Role
// - แก้ไข Password
//
// =====================================================

router.put(

    "/:id",

    authorize(
        ...ROLE.ADMIN
    ),

    UserController.update

);


// =====================================================
// DELETE USER
//
// DELETE:
//
// /api/users/:id
//
// =====================================================
//
// ROLE:
//
// ADMIN ONLY
//
// =====================================================
//
// Controller / Service
//
// จะมีการตรวจสอบเพิ่มเติม
//
// เช่น:
//
// - User มีอยู่จริงหรือไม่
// - ห้ามลบ Default Admin
//
// =====================================================

router.delete(

    "/:id",

    authorize(
        ...ROLE.ADMIN
    ),

    UserController.delete

);


// =====================================================
// ROUTE NOT FOUND
//
// ถ้ามี Request เข้า:
//
// /api/users/...
//
// แต่ไม่ตรงกับ Route ด้านบน
//
// ระบบตอบ:
//
// 404
//
// =====================================================

router.use(

    (
        req,
        res
    ) => {

        return res
            .status(
                404
            )
            .json({

                success:
                    false,

                message:
                    "User API route not found",

                path:
                    req.originalUrl

            });

    }

);


// =====================================================
// EXPORT ROUTER
//
// server.js:
//
// const userRoutes =
//     require("./routes/users");
//
// app.use(
//     "/api/users",
//     userRoutes
// );
//
// =====================================================

module.exports =
    router;